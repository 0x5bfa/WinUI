using System.Collections.Immutable;
using System.Text;
using Microsoft.UI.Xaml.Compiler.Semantics;
using Microsoft.UI.Xaml.Compiler.Syntax;

namespace Microsoft.UI.Xaml.Compiler.Generation;

public enum XamlTargetLanguage { CSharp, CppWinRT }

public sealed record GeneratedSource(string FileName, string Text);

public sealed record XamlGenerationResult(ImmutableArray<GeneratedSource> Files,
    ImmutableArray<XamlDiagnostic> Diagnostics)
{
    public bool Success => Diagnostics.IsEmpty;
}

public static class XamlSourceGenerator
{
    public static XamlGenerationResult Generate(BoundMarkup markup, XamlTypeCatalog catalog,
        XamlTargetLanguage language, string resourcePath)
    {
        ArgumentNullException.ThrowIfNull(markup);
        ArgumentNullException.ThrowIfNull(catalog);
        var diagnostics = markup.Diagnostics.ToList();
        if (markup.ClassName is null)
            diagnostics.Add(new("XMC2001", "x:Class is required to generate code-behind.", markup.Root.Location));
        if (string.IsNullOrWhiteSpace(resourcePath) || resourcePath.Contains("..", StringComparison.Ordinal))
            diagnostics.Add(new("XMC2002", "A valid application-relative XAML path is required.", markup.Root.Location));
        if (diagnostics.Count != 0)
            return new([], [.. diagnostics]);

        var className = markup.ClassName!;
        var separator = className.LastIndexOf('.');
        if (separator < 1 || separator == className.Length - 1)
            return new([], [new("XMC2003", "x:Class must include a namespace and class name.", markup.Root.Location)]);

        var namespaceName = className[..separator];
        var shortName = className[(separator + 1)..];
        var nodes = Walk(markup.Root).ToArray();
        var bindings = nodes.SelectMany(n => n.Members
            .Where(m => m.Binding is not null)
            .Select(m => (Element: n, Member: m))).ToArray();

        // Each compiled binding must be connected to an object by the runtime loader.
        if (bindings.Any(b => b.Member.OwnerType != b.Element.TypeName))
            diagnostics.Add(new("XMC2006", "Attached-property x:Bind requires an attached-property setter.", markup.Root.Location));
        if (diagnostics.Count != 0)
            return new([], [.. diagnostics]);

        var output = language switch
        {
            XamlTargetLanguage.CSharp => GenerateCSharp(namespaceName, shortName, markup.Root,
                nodes, bindings, catalog, resourcePath),
            XamlTargetLanguage.CppWinRT => GenerateCpp(namespaceName, shortName, markup.Root,
                nodes, bindings, catalog, resourcePath),
            _ => throw new ArgumentOutOfRangeException(nameof(language)),
        };
        return new([new(shortName + (language == XamlTargetLanguage.CSharp ? ".xaml.g.cs" : ".xaml.g.h"), output)], []);
    }

    private static IEnumerable<BoundElement> Walk(BoundElement node)
    {
        yield return node;
        foreach (var child in node.Children)
            foreach (var descendant in Walk(child)) yield return descendant;
        foreach (var property in node.Properties)
            foreach (var value in property.Values)
                foreach (var descendant in Walk(value)) yield return descendant;
    }

    private static string GenerateCSharp(string ns, string name, BoundElement root,
        BoundElement[] nodes, (BoundElement Element, BoundMember Member)[] bindings,
        XamlTypeCatalog catalog, string resourcePath)
    {
        var twoWayBindings = bindings.Where(b => b.Member.Binding!.Mode == XamlBindingMode.TwoWay).ToArray();
        var tracksChanges = bindings.Any(b => b.Member.Binding!.Mode != XamlBindingMode.OneTime);
        var supportsLifecycle = catalog.HasEvent(root.TypeName, "Loaded") && catalog.HasEvent(root.TypeName, "Unloaded");
        var output = new StringBuilder();
        output.AppendLine("// <auto-generated />");
        output.AppendLine("#nullable enable");
        output.Append("namespace ").Append(ns).AppendLine();
        output.AppendLine("{");
        output.Append("    partial class ").Append(name).Append(" : global::").Append(root.TypeName)
            .AppendLine(", global::Microsoft.UI.Xaml.Markup.IComponentConnector");
        output.AppendLine("    {");
        output.AppendLine("        private bool __xamlContentLoaded;");

        foreach (var node in nodes)
        {
            output.Append("        private global::").Append(node.TypeName)
                .Append("? __xc").Append(node.ConnectionId).AppendLine(";");
            if (node.Name is not null)
                output.Append("        internal global::").Append(node.TypeName).Append("? ")
                    .Append(node.Name).AppendLine(";");
        }

        if (tracksChanges)
        {
            output.AppendLine("        private bool __updatingBindings;");
            output.AppendLine("        private readonly global::System.Collections.Generic.List<(global::System.ComponentModel.INotifyPropertyChanged Source, global::System.ComponentModel.PropertyChangedEventHandler Handler)> __bindingSubscriptions = new();");
        }
        if (twoWayBindings.Length > 0)
            output.AppendLine("        private readonly global::System.Collections.Generic.List<(global::Microsoft.UI.Xaml.DependencyObject Target, global::Microsoft.UI.Xaml.DependencyProperty Property, long Token)> __twoWaySubscriptions = new();");

        output.AppendLine("        public void InitializeComponent()");
        output.AppendLine("        {");
        output.AppendLine("            if (__xamlContentLoaded) return;");
        output.AppendLine("            __xamlContentLoaded = true;");
        output.Append("            global::Microsoft.UI.Xaml.Application.LoadComponent(this, new global::System.Uri(\"ms-appx:///")
            .Append(Escape(resourcePath.Replace('\\', '/').TrimStart('/'))).AppendLine("\"));");
        if (bindings.Length != 0) output.AppendLine("            __UpdateBindings();");
        if (twoWayBindings.Length > 0)
            output.AppendLine("            __RegisterTwoWayBindings();");
        if (tracksChanges && supportsLifecycle)
        {
            output.AppendLine("            this.Unloaded += (_, _) =>");
            output.AppendLine("            {");
            output.AppendLine("                __UnsubscribeBindings();");
            if (twoWayBindings.Length > 0) output.AppendLine("                __UnregisterTwoWayBindings();");
            output.AppendLine("            };");
            output.AppendLine("            this.Loaded += (_, _) =>");
            output.AppendLine("            {");
            output.AppendLine("                __UpdateBindings();");
            if (twoWayBindings.Length > 0) output.AppendLine("                __RegisterTwoWayBindings();");
            output.AppendLine("            };");
        }
        output.AppendLine("        }");

        output.AppendLine("        public void Connect(int connectionId, object target)");
        output.AppendLine("        {");
        output.AppendLine("            switch (connectionId)");
        output.AppendLine("            {");
        foreach (var node in nodes)
        {
            output.Append("                case ").Append(node.ConnectionId).AppendLine(":");
            output.Append("                    __xc").Append(node.ConnectionId).Append(" = (global::")
                .Append(node.TypeName).AppendLine(")target;");
            if (node.Name is not null)
                output.Append("                    ").Append(node.Name).Append(" = __xc")
                    .Append(node.ConnectionId).AppendLine(";");
            foreach (var evt in node.Members.Where(m => catalog.HasEvent(m.OwnerType, m.Name) && m.Binding is null))
                output.Append("                    __xc").Append(node.ConnectionId).Append("!.")
                    .Append(evt.Name).Append(" += this.").Append(evt.Value).AppendLine(";");
            output.AppendLine("                    break;");
        }
        output.AppendLine("            }");
        output.AppendLine("        }");

        if (bindings.Length != 0)
        {
            output.AppendLine("        public void UpdateBindings() => __UpdateBindings();");
            output.AppendLine("        private void __UpdateBindings()");
            output.AppendLine("        {");
            if (bindings.Any(b => b.Member.Binding!.Mode != XamlBindingMode.OneTime))
            {
                output.AppendLine("            if (__updatingBindings) return;");
                output.AppendLine("            __updatingBindings = true;");
                output.AppendLine("            try");
                output.AppendLine("            {");
                output.AppendLine("                __UnsubscribeBindings();");
                var observed = bindings.Where(b => b.Member.Binding!.Mode != XamlBindingMode.OneTime)
                    .SelectMany(b => GetObservedPaths(b.Member.Binding!.Path))
                    .Distinct(StringComparer.Ordinal).ToArray();
                for (var i = 0; i < observed.Length; i++)
                {
                    output.Append("                if (").Append(observed[i]).Append(" is global::System.ComponentModel.INotifyPropertyChanged source")
                        .Append(i).AppendLine(")");
                    output.AppendLine("                {");
                    output.Append("                    global::System.ComponentModel.PropertyChangedEventHandler handler").Append(i)
                        .AppendLine(" = (_, _) => __UpdateBindings();");
                    output.Append("                    source").Append(i).Append(".PropertyChanged += handler").Append(i).AppendLine(";");
                    output.Append("                    __bindingSubscriptions.Add((source").Append(i).Append(", handler")
                        .Append(i).AppendLine("));");
                    output.AppendLine("                }");
                }
            }
            foreach (var binding in bindings)
            {
                output.Append("                if (__xc").Append(binding.Element.ConnectionId).AppendLine(" is not null)");
                output.Append("                    __xc").Append(binding.Element.ConnectionId).Append('.')
                    .Append(binding.Member.Name).Append(" = this.")
                    .Append(binding.Member.Binding!.Path).AppendLine(";");
            }
            if (bindings.Any(b => b.Member.Binding!.Mode != XamlBindingMode.OneTime))
            {
                output.AppendLine("            }");
                output.AppendLine("            finally { __updatingBindings = false; }");
            }
            output.AppendLine("        }");
        }

        if (bindings.Any(b => b.Member.Binding!.Mode != XamlBindingMode.OneTime))
        {
            output.AppendLine("        private void __UnsubscribeBindings()");
            output.AppendLine("        {");
            output.AppendLine("            foreach (var subscription in __bindingSubscriptions)");
            output.AppendLine("                subscription.Source.PropertyChanged -= subscription.Handler;");
            output.AppendLine("            __bindingSubscriptions.Clear();");
            output.AppendLine("        }");
        }

        if (twoWayBindings.Length > 0)
        {
            output.AppendLine("        private void __RegisterTwoWayBindings()");
            output.AppendLine("        {");
            output.AppendLine("            if (__twoWaySubscriptions.Count > 0) return;");
            foreach (var binding in twoWayBindings)
            {
                var id = binding.Element.ConnectionId;
                var type = binding.Element.TypeName;
                var property = binding.Member.Name;
                output.Append("            if (__xc").Append(id).AppendLine(" is { } target" + id + ")");
                output.AppendLine("            {");
                output.Append("                var property").Append(id).Append(" = global::").Append(type)
                    .Append('.').Append(property).AppendLine("Property;");
                output.Append("                var token").Append(id).Append(" = target").Append(id)
                    .Append(".RegisterPropertyChangedCallback(property").Append(id).AppendLine(", (_, _) =>");
                output.AppendLine("                {");
                output.AppendLine("                    if (__updatingBindings) return;");
                output.Append("                    this.").Append(binding.Member.Binding!.Path).Append(" = target")
                    .Append(id).Append('.').Append(property).AppendLine(";");
                output.AppendLine("                });");
                output.Append("                __twoWaySubscriptions.Add((target").Append(id).Append(", property")
                    .Append(id).Append(", token").Append(id).AppendLine("));");
                output.AppendLine("            }");
            }
            output.AppendLine("        }");
            output.AppendLine("        private void __UnregisterTwoWayBindings()");
            output.AppendLine("        {");
            output.AppendLine("            foreach (var subscription in __twoWaySubscriptions)");
            output.AppendLine("                subscription.Target.UnregisterPropertyChangedCallback(subscription.Property, subscription.Token);");
            output.AppendLine("            __twoWaySubscriptions.Clear();");
            output.AppendLine("        }");
        }

        output.AppendLine("    }");
        output.AppendLine("}");
        return output.ToString();
    }

    private static IEnumerable<string> GetObservedPaths(string path)
    {
        yield return "this";
        var parts = path.Split('.');
        for (var i = 1; i < parts.Length; i++)
            yield return "this." + string.Join('.', parts.Take(i));
    }

    private static string GenerateCpp(string ns, string name, BoundElement root,
        BoundElement[] nodes, (BoundElement Element, BoundMember Member)[] bindings,
        XamlTypeCatalog catalog, string resourcePath)
    {
        var tracksChanges = bindings.Any(b => b.Member.Binding!.Mode != XamlBindingMode.OneTime);
        var twoWayBindings = bindings.Where(b => b.Member.Binding!.Mode == XamlBindingMode.TwoWay).ToArray();
        var supportsLifecycle = catalog.HasEvent(root.TypeName, "Loaded") && catalog.HasEvent(root.TypeName, "Unloaded");
        var output = new StringBuilder();
        var cppNs = ns.Replace(".", "::", StringComparison.Ordinal);
        output.AppendLine("// <auto-generated />");
        output.AppendLine("#pragma once");
        if (tracksChanges)
        {
            output.AppendLine("#include <utility>");
            output.AppendLine("#include <vector>");
            output.AppendLine("#include <tuple>");
        }
        output.AppendLine("#include <winrt/Microsoft.UI.Xaml.h>");
        output.AppendLine("#include <winrt/Microsoft.UI.Xaml.Markup.h>");
        if (tracksChanges) output.AppendLine("#include <winrt/Microsoft.UI.Xaml.Data.h>");
        foreach (var header in nodes.Select(node => node.TypeName[..node.TypeName.LastIndexOf('.')]).Distinct(StringComparer.Ordinal))
        {
            output.Append("#include <winrt/").Append(header).AppendLine(".h>");
        }
        output.Append("namespace winrt::").Append(cppNs).AppendLine("::implementation");
        output.AppendLine("{");
        output.Append("    template <typename D, typename... I> struct ").Append(name)
            .Append("T : ::winrt::").Append(cppNs).Append("::implementation::").Append(name)
            .AppendLine("_base<D, ::winrt::Microsoft::UI::Xaml::Markup::IComponentConnector, I...>");
        output.AppendLine("    {");
        output.AppendLine("        bool _contentLoaded{ false };");
        if (tracksChanges)
        {
            output.AppendLine("        bool _updatingBindings{ false };");
            output.AppendLine("        std::vector<std::pair<::winrt::Microsoft::UI::Xaml::Data::INotifyPropertyChanged, ::winrt::event_token>> _bindingSubscriptions;");
        }
        if (twoWayBindings.Length > 0)
            output.AppendLine("        std::vector<std::tuple<::winrt::Microsoft::UI::Xaml::DependencyObject, ::winrt::Microsoft::UI::Xaml::DependencyProperty, int64_t>> _twoWaySubscriptions;");
        foreach (var node in nodes)
        {
            output.Append("        ").Append(CppType(node.TypeName)).Append(" _xc").Append(node.ConnectionId)
                .AppendLine("{ nullptr };");
            if (node.Name is not null)
                output.Append("        ").Append(CppType(node.TypeName)).Append(' ').Append(node.Name)
                    .Append("() const { return _xc").Append(node.ConnectionId).AppendLine("; }");
        }
        if (tracksChanges)
        {
            output.Append("        ~").Append(name).AppendLine("T()");
            output.AppendLine("        {");
            output.AppendLine("            UnsubscribeBindings();");
            if (twoWayBindings.Length > 0) output.AppendLine("            UnregisterTwoWayBindings();");
            output.AppendLine("        }");
        }
        output.AppendLine("        void InitializeComponent()");
        output.AppendLine("        {");
        output.AppendLine("            if (_contentLoaded) return;");
        output.AppendLine("            _contentLoaded = true;");
        output.Append("            ::winrt::Microsoft::UI::Xaml::Application::LoadComponent(*this, ")
            .Append("::winrt::Windows::Foundation::Uri(L\"ms-appx:///")
            .Append(Escape(resourcePath.Replace('\\', '/').TrimStart('/'))).AppendLine("\"));");
        if (bindings.Length > 0) output.AppendLine("            UpdateBindings();");
        if (twoWayBindings.Length > 0) output.AppendLine("            RegisterTwoWayBindings();");
        if (tracksChanges && supportsLifecycle)
        {
            output.AppendLine("            this->Unloaded([this](auto const&, auto const&)");
            output.AppendLine("            {");
            output.AppendLine("                UnsubscribeBindings();");
            if (twoWayBindings.Length > 0) output.AppendLine("                UnregisterTwoWayBindings();");
            output.AppendLine("            });");
            output.AppendLine("            this->Loaded([this](auto const&, auto const&)");
            output.AppendLine("            {");
            output.AppendLine("                UpdateBindings();");
            if (twoWayBindings.Length > 0) output.AppendLine("                RegisterTwoWayBindings();");
            output.AppendLine("            });");
        }
        output.AppendLine("        }");
        output.AppendLine("        void Connect(int32_t id, ::winrt::Windows::Foundation::IInspectable const& target)");
        output.AppendLine("        {");
        output.AppendLine("            switch (id)");
        output.AppendLine("            {");
        foreach (var node in nodes)
        {
            output.Append("            case ").Append(node.ConnectionId).AppendLine(":");
            output.Append("                _xc").Append(node.ConnectionId).Append(" = target.as<")
                .Append(CppType(node.TypeName)).AppendLine(">();");
            foreach (var evt in node.Members.Where(m => catalog.HasEvent(m.OwnerType, m.Name) && m.Binding is null))
                output.Append("                _xc").Append(node.ConnectionId).Append('.').Append(evt.Name)
                    .Append("({ static_cast<D*>(this), &D::").Append(evt.Value).AppendLine(" });");
            output.AppendLine("                break;");
        }
        output.AppendLine("            }");
        output.AppendLine("        }");
        if (bindings.Length != 0)
        {
            output.AppendLine("        void UpdateBindings()");
            output.AppendLine("        {");
            if (tracksChanges)
            {
                output.AppendLine("            if (_updatingBindings) return;");
                output.AppendLine("            _updatingBindings = true;");
                output.AppendLine("            try");
                output.AppendLine("            {");
                output.AppendLine("                UnsubscribeBindings();");
                var paths = bindings.Where(b => b.Member.Binding!.Mode != XamlBindingMode.OneTime)
                    .SelectMany(b => GetObservedPaths(b.Member.Binding!.Path))
                    .Where(path => path != "this").Distinct(StringComparer.Ordinal).ToArray();
                for (var i = 0; i < paths.Length; i++)
                {
                    var cppPath = CppPath(paths[i][5..]);
                    output.Append("                if constexpr (requires { static_cast<D*>(this)->")
                        .Append(cppPath).AppendLine(".template try_as<::winrt::Microsoft::UI::Xaml::Data::INotifyPropertyChanged>(); })");
                    output.AppendLine("                {");
                    output.Append("                    if (auto source = static_cast<D*>(this)->")
                        .Append(cppPath).AppendLine(".template try_as<::winrt::Microsoft::UI::Xaml::Data::INotifyPropertyChanged>())");
                    output.AppendLine("                    {");
                    output.AppendLine("                        auto token = source.PropertyChanged([this](auto const&, auto const&) { UpdateBindings(); });");
                    output.AppendLine("                        _bindingSubscriptions.emplace_back(source, token);");
                    output.AppendLine("                    }");
                    output.AppendLine("                }");
                }
            }
            foreach (var binding in bindings)
                output.Append("            if (_xc").Append(binding.Element.ConnectionId).Append(") _xc")
                    .Append(binding.Element.ConnectionId).Append('.').Append(binding.Member.Name)
                    .Append("(static_cast<D*>(this)->").Append(CppPath(binding.Member.Binding!.Path))
                    .AppendLine(");");
            if (tracksChanges)
            {
                output.AppendLine("            }");
                output.AppendLine("            catch (...) { _updatingBindings = false; throw; }");
                output.AppendLine("            _updatingBindings = false;");
            }
            output.AppendLine("        }");
        }
        if (tracksChanges)
        {
            output.AppendLine("        void UnsubscribeBindings()");
            output.AppendLine("        {");
            output.AppendLine("            for (auto const& [source, token] : _bindingSubscriptions) source.PropertyChanged(token);");
            output.AppendLine("            _bindingSubscriptions.clear();");
            output.AppendLine("        }");
        }
        if (twoWayBindings.Length > 0)
        {
            output.AppendLine("        void RegisterTwoWayBindings()");
            output.AppendLine("        {");
            output.AppendLine("            if (!_twoWaySubscriptions.empty()) return;");
            foreach (var binding in twoWayBindings)
            {
                var id = binding.Element.ConnectionId;
                var property = binding.Member.Name;
                output.Append("            if (_xc").Append(id).AppendLine(")");
                output.AppendLine("            {");
                output.Append("                auto target = _xc").Append(id)
                    .AppendLine(".try_as<::winrt::Microsoft::UI::Xaml::DependencyObject>();");
                output.AppendLine("                if (target)");
                output.AppendLine("                {");
                output.Append("                    auto property = ").Append(CppType(binding.Element.TypeName))
                    .Append("::").Append(property).AppendLine("Property();");
                output.AppendLine("                    auto token = target.RegisterPropertyChangedCallback(property, [this](auto const&, auto const&)");
                output.AppendLine("                    {");
                output.AppendLine("                        if (_updatingBindings) return;");
                output.Append("                        static_cast<D*>(this)->")
                    .Append(CppSetter(binding.Member.Binding!.Path, "_xc" + id + "." + property + "()"))
                    .AppendLine(";");
                output.AppendLine("                    });");
                output.AppendLine("                    _twoWaySubscriptions.emplace_back(target, property, token);");
                output.AppendLine("                }");
                output.AppendLine("            }");
            }
            output.AppendLine("        }");
            output.AppendLine("        void UnregisterTwoWayBindings()");
            output.AppendLine("        {");
            output.AppendLine("            for (auto const& [target, property, token] : _twoWaySubscriptions)");
            output.AppendLine("                target.UnregisterPropertyChangedCallback(property, token);");
            output.AppendLine("            _twoWaySubscriptions.clear();");
            output.AppendLine("        }");
        }
        output.AppendLine("    };");
        output.AppendLine("}");
        return output.ToString();
    }

    private static string CppType(string type) => "::winrt::" + type.Replace(".", "::", StringComparison.Ordinal);
    private static string CppPath(string path) => string.Join('.', path.Split('.').Select(segment => segment + "()"));
    private static string CppSetter(string path, string value)
    {
        var separator = path.LastIndexOf('.');
        return (separator < 0 ? "" : CppPath(path[..separator]) + ".") + path[(separator + 1)..] + "(" + value + ")";
    }
    private static string Escape(string value) => value.Replace("\\", "\\\\", StringComparison.Ordinal)
        .Replace("\"", "\\\"", StringComparison.Ordinal);
}
